def run_pipeline(config: ExperimentConfig | None = None):
    config = config or ExperimentConfig()
    config.validate()
    output = Path(config.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    print(f"[{_timestamp()}] PHASE1B | selecting hyperparameters without midpoint outcomes", flush=True)
    selection, selected = select_hyperparameters(
        config, progress=lambda message: print(f"[{_timestamp()}] PHASE1B | {message}", flush=True))
    selection.to_csv(output / "phase1b_hyperparameter_selection.csv", index=False)

    training_summary, seed_metrics, sweeps, patches = [], [], [], []
    fine_trajectory, midpoint_trajectory, familiar_schedule, full_schedule = [], [], [], []
    original_hashes = {}
    checkpoint_dir = output / "checkpoints"
    for seed in config.seeds:
        high, high_cache = load_source(config, "D0_frozen_high", seed)
        low, low_cache = load_source(config, "D6_frozen_low", seed)
        original_hashes[str(high.path)] = high.checkpoint_sha256
        original_hashes[str(low.path)] = low.checkpoint_sha256
        models = {"D0_frozen_high": (high.model, high_cache),
                  "D6_frozen_low": (low.model, low_cache)}
        for baseline, cache in (("D0_frozen_high", high_cache), ("D6_frozen_low", low_cache)):
            training_summary.append({
                "condition": baseline, "seed": seed, "path_kind": "none",
                "alpha": 0., "beta": 0., "gamma": 0., "optimizer_steps": 0,
                "training_lambdas": "", "midpoint_training_steps": 0,
                "midpoint_used_for_selection": False, "human_rows_used": 0,
                "source_checkpoint": cache.checkpoint_path,
                "source_checkpoint_sha256": cache.checkpoint_sha256,
                "source_model_sha256": cache.source_model_sha256,
                "final_model_sha256": cache.source_model_sha256,
                "output_head_frozen_exact": True,
            })
        for condition in TRAINED_CONDITIONS:
            hyper = selected[condition]
            result = train_condition(
                config, condition, seed, high.model, high_cache,
                hyper["alpha"], hyper["beta"], hyper["gamma"], record=True,
                progress=lambda message: print(f"[{_timestamp()}] PHASE1B | {message}", flush=True))
            models[condition] = (result.model, high_cache)
            training_summary.append(result.summary)
            fine_trajectory.extend(result.trajectory)
            midpoint_trajectory.extend(result.midpoint)
            if config.save_checkpoints:
                _atomic_torch_save({
                    "condition": condition, "seed": seed,
                    "source_checkpoint": high_cache.checkpoint_path,
                    "source_checkpoint_sha256": high_cache.checkpoint_sha256,
                    "hyperparameters": hyper,
                    "output_head_frozen": True,
                    "model_state_dict": {k: v.detach().cpu().clone()
                                         for k, v in result.model.state_dict().items()},
                    "policy_state_dict": (
                        {k: v.detach().cpu().clone()
                         for k, v in high_cache.policy.state_dict().items()}
                        if high_cache.policy is not None else None),
                }, checkpoint_dir / f"{condition}_seed_{seed}.pt")
        for condition in ALL_CONDITIONS:
            model, cache = models[condition]
            metric, cue, patch = evaluate_model(config, condition, seed, model, cache)
            seed_metrics.append(metric); sweeps.extend(cue); patches.extend(patch)
            familiar, full = replay_schedules(config, condition, seed, model, cache)
            familiar_schedule.extend(familiar); full_schedule.extend(full)
        print(f"[{_timestamp()}] PHASE1B | completed seed {seed}", flush=True)

    # T1: originals must remain byte-identical after all fine-tuning and output writes.
    for path, before in original_hashes.items():
        after = sha256_file(Path(path))
        if before != after:
            raise AssertionError(f"T1 failed: original checkpoint changed: {path}")

    metric_frame = pd.DataFrame(seed_metrics)
    patch_frame = pd.DataFrame(patches)
    master, endpoint, path_metrics, rescue = synthesize_metrics(metric_frame, patch_frame)
    gate, overall_pass = phase1b_gate(config, master)
    tables = {
        "phase1b_training_summary": pd.DataFrame(training_summary),
        "phase1b_seed_metrics": master,
        "phase1b_endpoint_preservation": endpoint,
        "phase1b_path_metrics": path_metrics,
        "phase1b_cue_sweep": pd.DataFrame(sweeps),
        "phase1b_patching": patch_frame,
        "phase1b_rescue_fraction": rescue,
        "phase1b_timeseries_finetuning": pd.DataFrame(fine_trajectory),
        "phase1b_timeseries_familiar_full_schedule": pd.DataFrame(familiar_schedule),
        "phase1b_timeseries_full_experiment": pd.DataFrame(full_schedule),
        "phase1b_timeseries_midpoint_checkpoints": pd.DataFrame(midpoint_trajectory),
    }
    for name in REQUIRED_CSVS:
        tables[name].to_csv(output / f"{name}.csv", index=False)
    gate.to_csv(output / "phase1b_gate.csv", index=False)
    if config.make_plots:
        make_figures(output, tables, config.updates)
        enforce_mandatory_timeseries(output)
    else:
        raise RuntimeError("T13: report generation requires all mandatory time-series figures.")
    _report(output, tables, gate, overall_pass, selected)
    manifest = {
        "config": config.manifest(), "selected_hyperparameters": selected,
        "PHASE1B_GATE": "PASS" if overall_pass else "FAIL",
        "condition_gate": gate.groupby("condition").passed.all().to_dict(),
        "selection_used_midpoint": False, "selection_used_human_data": False,
        "human_data_used": False, "original_checkpoint_hashes_preserved": True,
        "midpoint_training_steps_primary": 0,
        "structured_ecology_authorized": bool(overall_pass),
    }
    (output / "experiment_manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"[{_timestamp()}] PHASE1B | complete: gate={'PASS' if overall_pass else 'FAIL'}", flush=True)
    return {**tables, "phase1b_gate": gate, "manifest": manifest,
            "hyperparameter_selection": selection}
