"""Trusted worker entry point. Executes only the registered native candidate grammar."""
import argparse,copy,json,time,traceback,os,random
from pathlib import Path
import numpy as np,pandas as pd,torch
from research_search.common import *
from research_search.orchestration.store import Store
from research_search.orchestration.budget import BudgetError
from research_search.runners.candidate import *
from research_search.runners.train import NativeRuntime
from research_search.evaluation.scoring import score,observations,PROBES

def execute(directory,job):
    campaign=Path(directory).resolve();limits=read(campaign/'budgets.json');store=Store(campaign,limits);payload=json.loads(job['payload']);config=validate(payload['config']);identity=payload['identity'];dest=campaign/'jobs'/job['id'];dest.mkdir(parents=True,exist_ok=True);seed=payload['seed'];torch.manual_seed(seed);np.random.seed(seed);random.seed(seed)
    if payload['kind']=='cached_fixture':
        path=Path(payload['prediction_file']).resolve()
        if not path.is_relative_to(campaign) or sha(path)!=payload['prediction_sha']:raise ValueError('Unverified cached fixture')
        a=np.load(path);f,p=observations(a['logits'],a['updates'],a['path'],seed,job['candidate']);f.to_csv(dest/'metrics.csv',index=False);p.to_csv(dest/'positions.csv',index=False);return dict(passed=True,kind='cached_fixture',new_optimizer_steps=0,position_rows=len(p))
    model=build_model(config,seed)
    runtime=NativeRuntime(store,job['id'],dest,config,seed,identity,deadline=time.monotonic()+max(1,float(os.environ.get('RESEARCH_WALL_SECONDS','1200'))-5),fixture_steps=payload.get('fixture_steps'));runtime.attach(model)
    if payload.get('prior_file'):
        p=Path(payload['prior_file']).resolve()
        if not p.is_relative_to(campaign/'jobs') or sha(p)!=payload['prior_sha']:raise ValueError('Unverified prior cache path')
        prior=torch.load(p,weights_only=False);model.load_state_dict(prior['model'])
        from experiments.joint_phenotype_hypothesis_screen.common import set_rng
        set_rng(prior['rng'])
    if payload['kind'] in ['prior','competence']:
        tasks=payload['tasks'];model=run_pretraining(model,config,tasks)
        if payload['kind']=='competence':
            from experiments.context_experience_prior import core
            cp=torch.load(dest/'progress.pt',weights_only=False);model,_,_=runtime.restore(cp,False);rows=[]
            for c in sorted({r['context'] for r in tasks[0]['updates']}):
                s=core.trace(model,c,tasks[0]['paths'][0]);rows.append(dict(context=c,ce=float(s['ce'].mean()),correct_count=int(s['accuracy'].sum()),useful=bool(s['ce'].mean()<=.5 and s['accuracy'].sum()>=6)))
            write(dest/'competence.json',dict(rows=rows,all_practiced_contexts_useful=all(r['useful'] for r in rows),criterion='inherited CE<=.5 and integer>=6/7 after20 ordinary unrelated-task updates'),True)
        return dict(passed=True,kind='prior',attempts=runtime.k,destination=str(dest),model_sha=sha(dest/'pretrained.pt'))
    result=run_target_learning(model,config,payload['task']);arr=np.load(result['predictions']);f,p=observations(arr['logits'],arr['updates'],arr['path'],seed,job['candidate'])
    f.to_csv(dest/'metrics.csv',index=False);p.to_csv(dest/'positions.csv',index=False)
    from research_search.evaluation.cached import quarter_readout
    cp=torch.load(dest/'progress.pt',weights_only=False);bias=np.stack([cp['extra']['states'][int(n)]['model']['sequence_head.bias'].numpy() for n in arr['updates']]);sf,sp=quarter_readout(arr['logits'],bias,arr['updates'],arr['path'],seed,job['candidate']);sf.to_csv(dest/'static_readout_metrics.csv',index=False);sp.to_csv(dest/'static_readout_positions.csv',index=False)
    if payload.get('fixture_steps'):summary=dict(fixture_only=True,complete_scientific_trajectory=False,gate_status='unassessed_fixture',seed=seed,task_id=payload['task']['task_id'])
    else:
        result=score(arr['logits'],arr['updates'],arr['path'],seed,job['candidate']);summary=result['summary']|dict(task_id=payload['task']['task_id'],phase=payload['phase']);static_end=sf[sf['update'].eq(330)].set_index('cue')
        for name in ['C','NoContext','Mixed-average']:
            for metric in ['ce','accuracy']:summary['static_view_'+name+'_'+metric]=float(static_end.loc[name,metric])
        for name in ['blocks','switch_costs','matched_acquisition']:result[name].to_csv(dest/(name+'.csv'),index=False)
    write(dest/'evaluation.json',summary,True)
    # Every physical Mixed is generated by the actual source forward. In the
    # additive case independently check double midpoint and CE convexity.
    if config['model']['activation']=='linear' and not config['model']['gate']:
        from experiments.context_experience_prior import core
        from .candidate import export_predictions
        from research_search.evaluation.linear import controls
        cp=torch.load(dest/'progress.pt',weights_only=False);checks=[]
        for n in [0,10,20,40,60,100,170,330]:
            if n not in cp['extra']['states']:continue
            m=build_model(config,seed).double();m.load_state_dict(cp['extra']['states'][n]['model']);d=export_predictions(m,payload['task']);check=controls(cp['extra']['states'][n]['model'],cp['extra']['observations'][n],cp['extra']['hidden_observations'][n],d,payload['task'],config['model']['cue_timing']=='onset');checks.append(dict(update=n,**check))
        write(dest/'linear_controls.json',dict(passed=True,checks=checks),True)
    return dict(passed=True,kind='target',attempts=runtime.k,destination=str(dest),evaluation=clean(summary))

def partial(directory,job):
    """Export only completed saved states; absent evaluations remain explicit."""
    campaign=Path(directory);dest=campaign/'jobs'/job['id'];cpfile=dest/'progress.pt';payload=json.loads(job['payload'])
    if payload.get('kind')!='target':return
    if not cpfile.exists():
        failed=sorted(dest.glob('failed_state_*.pt'),key=lambda p:int(p.stem.rsplit('_',1)[1]))
        if failed:cpfile=failed[-1]
    observed={}
    if cpfile.exists():
        cp=torch.load(cpfile,weights_only=False);extra=cp['extra'];observed=extra.get('observations',{})
        if observed:
            updates=sorted(observed);f,p=observations(np.stack([observed[n] for n in updates]),updates,payload['task']['path'],payload['seed'],job['candidate'],allow_nonfinite=True);f.to_csv(dest/'partial_metrics.csv',index=False);p.to_csv(dest/'partial_positions.csv',index=False)
    dest.mkdir(parents=True,exist_ok=True);pd.DataFrame([dict(update=k,cue=c,status='available_completed_state' if k in observed else 'missing_not_run_or_failed',scientific_gate='unassessed_incomplete') for k in range(331) for c in PROBES]).to_csv(dest/'planned_coverage.csv',index=False)

def main():
    p=argparse.ArgumentParser();p.add_argument('--campaign',required=True);p.add_argument('--job',required=True);args=p.parse_args();campaign=Path(args.campaign);job=read(campaign/'requests'/f'{identifier(args.job)}.json');torch.set_num_threads(1);torch.use_deterministic_algorithms(True)
    try:
        if json.loads(job['payload']).get('kind')=='cached_fixture':
            from experiments.a06_novel_cue_followup.verify import no_scientific_execution
            with no_scientific_execution():result=execute(campaign,job)
        else:result=execute(campaign,job)
    except BudgetError as ex:partial(campaign,job);result=dict(passed=False,status='paused_or_stopped',reason=str(ex))
    except BaseException as ex:partial(campaign,job);result=dict(passed=False,status='technical_or_numerical_failure',reason=repr(ex),traceback=traceback.format_exc(),no_automatic_retry=True)
    import uuid
    attempt=os.environ.get('RESEARCH_ATTEMPT_ID','manual-'+uuid.uuid4().hex)
    write(campaign/'worker_receipts'/args.job/f'{identifier(attempt)}.json',result,True);print(json.dumps(clean(result)))
    raise SystemExit(0 if result.get('passed') else 3)
if __name__=='__main__':main()
