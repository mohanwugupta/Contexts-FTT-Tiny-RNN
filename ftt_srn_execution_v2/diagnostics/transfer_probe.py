"""Frozen cross-context transfer diagnostic for split recurrent states."""

from __future__ import annotations

import pandas as pd
import torch
from torch.nn import functional as F

from ..config import FIXED_SEQUENCE
from ..inputs.context_basis import context_vector
from ..inputs.token_onehot import encode_sequence


def _state_before_position(model, tokens, context_name: str, position: int):
    if position == 0:
        return None
    context = context_vector(context_name, as_tensor=True).unsqueeze(0)
    _, _, _, state = model(tokens[:, :position], context)
    return state


def cross_context_transfer(model, *, checkpoint: str) -> pd.DataFrame:
    """Measure target-context prediction disruption from a source-context state.

    Each current token and target context is held fixed.  Only the recurrent
    state generated by the preceding prefix changes, making this a proper
    frozen counterfactual rather than another training condition.
    """
    tokens = encode_sequence(FIXED_SEQUENCE[:-1], as_tensor=True).unsqueeze(0)
    targets = torch.as_tensor(FIXED_SEQUENCE[1:], dtype=torch.long)
    rows = []
    model.eval()
    with torch.no_grad():
        for source, target in (("A", "B"), ("B", "A")):
            target_context = context_vector(target, as_tensor=True).unsqueeze(0)
            for position in range(1, tokens.shape[1]):
                source_state = _state_before_position(model, tokens, source, position)
                matched_state = _state_before_position(model, tokens, target, position)
                current = tokens[:, position:position + 1]
                crossed_logits, crossed_speed, _, _ = model(current, target_context, source_state)
                matched_logits, matched_speed, _, _ = model(current, target_context, matched_state)
                y = targets[position].view(1)
                crossed_ce = F.cross_entropy(crossed_logits[:, 0], y)
                matched_ce = F.cross_entropy(matched_logits[:, 0], y)
                rows.append({
                    "checkpoint": checkpoint,
                    "source_context": source,
                    "target_context": target,
                    "token_position": position + 1,
                    "matched_sequence_ce": float(matched_ce),
                    "cross_context_sequence_ce": float(crossed_ce),
                    "cross_context_transfer_cost": float(crossed_ce - matched_ce),
                    "absolute_cross_context_disruption": float(abs(crossed_ce - matched_ce)),
                    "cross_context_speed_change": float(crossed_speed.item() - matched_speed.item()),
                    "probe_optimizer_updates": 0,
                })
    detail = pd.DataFrame(rows)
    aggregate = detail.groupby(["checkpoint", "source_context", "target_context"], as_index=False).agg(
        matched_sequence_ce=("matched_sequence_ce", "mean"),
        cross_context_sequence_ce=("cross_context_sequence_ce", "mean"),
        cross_context_transfer_cost=("cross_context_transfer_cost", "mean"),
        absolute_cross_context_disruption=("absolute_cross_context_disruption", "mean"),
        cross_context_speed_change=("cross_context_speed_change", "mean"),
        n_positions=("token_position", "size"),
    )
    aggregate["probe_optimizer_updates"] = 0
    return aggregate
